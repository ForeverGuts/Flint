/**
 * 计划模式 —— ROADMAP 10.4.1 的程序侧。
 * 调用方：harness/main.ts（注册 before_tool_call 核心钩子 = **最前一道模式闸**）、
 *         commands/builtin/plan.ts（/plan，用户显式开关）、
 *         runtime/runtime.ts（每轮把横幅渲染进 task 层）
 * 服务于：把"动手前先对齐"从提示词自觉升级为**程序闸** ——
 *         用户开启后，模型**改不动任何项目文件**，只能先交方案。
 *
 * ── 缺口原样 ──
 * 此前模型拿到任务就开干：先改三个文件，再回来讲它打算怎么做。方向错了，那三个文件
 * 已经改完了 —— 用户要付一次"回退 + 重讲"的成本。提示词里写"先对齐再动手"是**软约束**
 * （强度 = 模型听不听话），而这一条要的是"**它想动手也动不了**"。
 *
 * ── 它拦什么：**能改用户项目文件的三条通道** ──
 *   · `write` / `edit` —— 目标路径就是文件本身，直接拦；
 *   · `bash` —— **刻意一起拦**，尽管 10.9.3 因为"读和写长得一样"把它**排除**在外。
 *     两处结论相反、理由不矛盾：那边的代价是**误拦正常命令**（`grep x /etc/hosts` 会被
 *     当成写），违反"宁可少拦不可误拦"；这里的代价只是"计划期间不能跑命令"，而
 *     **读能力全都有专用工具**（ls / read / grep / git），所以拦 bash 几乎不损失什么。
 *     反过来若不拦，`bash "echo x > src/a.ts"` 就是一条**现成的洞** —— 一个能被一句话
 *     绕过的闸，比没有闸更坏：它让人以为自己已经被保护住了。**所以这一条宁可全拦。**
 *   · 其余工具（ls / read / grep / git 只读、`ask`）**天然只读**，不进闸；
 *   · `todo` / `memory` / `record_event` / `archive` **刻意不进闸** —— 它们写的是
 *     `TASK.md` / `.flint/` 下**Agent 自己的笔记本**，不是用户的代码。计划模式要求
 *     "先把方案摆出来"，而记账（写下计划、记下结论）正是做这件事的一部分。
 *     界线一句话：**闸管"改用户的文件"，不管"Agent 记自己的账"。**
 *
 * ── 为什么排在四道闸**之前**（次序是设计，不是顺手）──
 * 其余各闸的**出路在计划模式下都不成立**：模型若拿到"请让用户 /charter unlock"或者
 * "请让用户 /workspace allow <目录>"，用户照做之后它**照样被这道闸拦着** —— 那就是
 * **方向给错**，而"方向给错比不给更坏"（同 10.9.5 的拒因分工）。
 * 所以模式闸先说话：它给出的唯一出路（"先把方案写出来"）在当前状态下**真的能走通**。
 * 代价是计划模式开启时审计只记 tag=plan（其它闸压根没轮到）—— 这恰好是事实。
 *
 * ── C8 的答法（这是本条与路线图原设想**最大的分歧**）──
 * C8 记的担忧是：*"计划模式在 RPC 下会形同虚设 —— 确认闸是人类交互，而 RPC 非 TTY 模式
 * 权限当前自动放行"*。那个担忧建立在一个**前提**上：计划模式 = **每一步都要人点头**。
 * 本设计里**根本没有"点头"这一步**：用户开一次模式（一条命令），之后**每一步都是程序判定**，
 * 不弹任何窗、不等任何人。于是 RPC / 非 TTY 下**没有任何东西可被"自动放行"** —— 闸照旧生效。
 * 一句话：C8 问的"确认闸"在本条里**不存在**，所以它担忧的那条失效路径也**不存在**。
 * （同样的取舍在 10.9.3 做过一次：外写放行刻意**不接权限弹窗**，理由就是非 TTY 下弹窗
 *  自动放行会让边界静默失效。这里是同一个论证的第二次应用。）
 * ⚠ 残留边界（不装糊涂）：开关**本身**是命令，能不能在 RPC 侧敲出来取决于命令通道是否
 *   暴露给调用方 —— 那是协议层的事，不在本闸的判据里。
 *
 * ── 会话级单例，刻意不持久化 ──
 * 与 `charterLock` / `workspaceGrants` 同源：一次"先看看方案"的临时意愿**不该**被放大成
 * "以后每次启动都只读"。要再进计划模式，用户再敲一次 `/plan on` —— 多打一个词的代价，
 * 换掉"上次忘了退出、这次它什么都不肯动手"这种最难查的故障。
 *
 * ── 已知边界（不装糊涂）──
 * · **它不是沙箱**：只对**经模型之手**的工具调用生效。用户在终端里自己敲命令，
 *   或者模型跑 `bash`（被拦了）之外的通路（比如将来新增的写类工具）都不在覆盖内。
 * · **新增写类工具时名单要跟着长** —— 名单是**封闭枚举**，漏一个就是一条静默通路。
 *   套件里有一条源码守护钉着"名单恰好是这三个"，就是给这件事留的提醒。
 * · 只挡"改"，不挡"读" —— 计划模式**鼓励**多读（这正是它想要的：先看清再提方案）。
 *
 * 零运行时依赖：只用本项目类型 + 纯函数。
 */
import type { HookDeny } from './tool-hooks.js';

/** 拒因与前缀 —— 套件靠它认出"是这道闸给的拒绝"（同 10.9.2 的 `[危险命令拦截]`） */
export const PLAN_MARK = '[计划模式]';

/**
 * 计划模式下不许执行的工具。**封闭枚举，加写类工具时必须同步这里**
 * （理由见文件头"已知边界"，套件有源码守护钉住这份名单的内容）。
 */
export const PLAN_BLOCKED_TOOLS: ReadonlySet<string> = new Set(['write', 'edit', 'bash']);

/** 该工具是否属于"能改用户项目文件"的那三条通道之一 */
export function isPlanBlockedTool(toolName: string): boolean {
  return PLAN_BLOCKED_TOOLS.has(toolName);
}

/**
 * 计划模式的**闸判据** —— 纯函数，模式由参数注入（与 `guardContractWrite` 同一立场：
 * 状态是参数、不是模块级直读，于是每条分支都能构造着打靶）。
 *
 * 判据只有两问，**刻意不看参数**：① 模式开着吗？② 工具名在名单里吗？
 * 因为"能不能改用户文件"这件事**由工具身份决定，不由这次的参数决定** ——
 * 于是本闸天然不会踩另外三道闸那些坑（参数形状不对 / 路径判不出来 / 命令读不懂），
 * 也没有 fail-open 的余地：参数长什么样都不影响结论。
 */
export function guardPlanMode(toolName: string, enabled: boolean): HookDeny | undefined {
  if (!enabled) return undefined;
  if (!PLAN_BLOCKED_TOOLS.has(toolName)) return undefined;
  return { action: 'deny', reason: renderPlanReason(toolName) };
}

/**
 * 教学拒因 —— 与 `renderDangerReason` / `renderWorkspaceReason` **同形**（同族的拒绝
 * 读起来该像一家人）：命中什么 · 这一条**没被执行** · 出路 · 末段自认边界。
 *
 * 出路只有一条，而且**必须是真的能走通的那一条**：把方案讲给用户看，由用户决定
 * 要不要 `/plan off`。**刻意不提**"你可以问问用户要不要关掉"之外的任何绕道 ——
 * 这里没有第二条路，编一条出来就是"方向给错"。
 */
export function renderPlanReason(toolName: string): string {
  return [
    `${PLAN_MARK} 这条调用没有被执行：现在是计划模式，用户只要方案、不要改动。`,
    `  被拦下的工具 = ${toolName}（能改项目文件的通道：write / edit / bash）`,
    '  出路：',
    '    · 你要做的事**已经够写方案了** —— 用 ls / read / grep / git 把情况看全，'
      + '然后把「打算改哪些文件、每个文件改什么、为什么这么改、怎么验证」写成给用户看的方案；',
    '    · 用户看过方案后自己敲 /plan off 退出计划模式，你才能动手。**这一步只有用户能做**；',
    '    · 方案里需要用户拍板的地方，用 ask 工具问（它不受本闸限制）。',
    '  （说明：这道闸只管 write / edit / bash 三条改文件的通道；'
      + '读、检索、git 只读、以及 todo / memory / record_event 这些"记自己的账"都不拦。'
      + '它不是沙箱。）',
  ].join('\n');
}

/**
 * 计划模式的**注入横幅** —— runtime 每轮渲染进 task 层（随 `ctx.plan` 传入）。
 *
 * 为什么要主动注入、而不是等它撞一次墙：这正是 10.2.1 的立场 —— **把规矩放进视野，
 * 比事后纠正便宜**。不注入的话，模型每轮都要先浪费一次 write 被拒才知道自己在计划模式，
 * 而它连试三次（write / edit / bash）就是三轮白烧。"让人看得见"永远比"让它撞一次"好。
 */
export function renderPlanBanner(): string {
  return [
    `${PLAN_MARK}（由用户开启，会话内有效）：**只读、先出方案**。`,
    '  现在 write / edit / bash 会被程序拒绝，直到用户敲 /plan off。',
    '  你要做的是：用只读工具把情况看全，把方案讲给用户看；需要拍板的地方用 ask 问。',
  ].join('\n');
}

/**
 * 计划模式开关 —— 会话级单例（进程内）。**刻意不落盘**（理由见文件头）。
 *
 * 写入口只有两个，**可信度来源不同，所以刻意是两个方法**（别顺手合成一个 toggle）：
 *   · `enter()` / `exit()` —— **用户开关**：唯一调用方是 `/plan` 命令。模型手里
 *     **没有任何工具碰得到这里**（命令只能由用户输入触发），所以"模型自己关掉闸再动手"
 *     这条路不存在 —— 与 `/charter unlock` / `/workspace allow` 同一分工；
 *   · `reset()` —— **复位**：给验证脚本在用例之间擦干净单例状态（同 `charterLock.reset`）。
 *     ⚠ 它**不是**"切项目时重启状态"用的：切项目**不该**动这个模式（用户开着计划模式
 *     去切了个项目，仍然在规划阶段），所以 `seedProjectContext()` 里**刻意没有**它。
 */
export const planMode = {
  on: false,

  /** 进入计划模式（由 /plan on 调用；这是**唯一**的开启动作） */
  enter(): void {
    this.on = true;
  },

  /** 退出计划模式（由 /plan off 调用；这是**唯一**的关闭动作） */
  exit(): void {
    this.on = false;
  },

  isOn(): boolean {
    return this.on;
  },

  /** 复位 —— 仅供验证脚本在用例之间擦干净单例状态 */
  reset(): void {
    this.on = false;
  },
};
