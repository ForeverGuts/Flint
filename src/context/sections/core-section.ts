/**
 * 基础规则段落 —— Agent 的行为准则（迁移自 runtime.ts 硬编码）。
 * 调用方：SystemPromptService（配置的 sections 之一）
 * 服务于：定义 Agent"怎么干活"的核心规则（何时调工具/如何完成任务）
 */
import type { SectionFn } from '../system-prompt.js';

/** 基础规则段（始终返回，作为核心准则） */
export const coreSection: SectionFn = () => `【最优先】普通对话、闲聊、提问建议、讨论概念时，直接回答，绝不调用任何工具。
工具只在你明确需要操作文件、执行命令、搜索代码时才调用——用户没明确要求时，禁止调用。
- 需要工具时，通过 tool_calls 结构化调用（工具名 + JSON 参数会自动发给系统执行）
- 工具结果会以 tool 消息返回给你
- 如果任务还没完成（如刚创建完文件需要运行测试），继续调下一个工具
- 全部做完后再给用户最终回答
- ⚠️ 口述"我创建了文件"不等于真的创建了文件，必须调工具才算
- 不要在调工具之前就回复"已创建"——工具没执行，文件不存在`;
